#!/usr/bin/env php
<?php

declare(strict_types=1);

/** Build the active Forum styles without changing the archived Imladris import. */
$arguments = array_slice($argv, 1);
$check = $arguments === ['--check'];
if ($arguments !== [] && !$check) {
    fwrite(STDERR, "Usage: php bin/build-forum-css.php [--check]\n");
    exit(2);
}

$root = dirname(__DIR__);
$read = static function (string $name) use ($root): string {
    $path = $root . '/resources/forum/' . $name;
    $content = file_get_contents($path);
    if ($content === false) {
        throw new RuntimeException('Cannot read Forum source: ' . $name);
    }
    return rtrim(str_replace("\r\n", "\n", $content)) . "\n";
};

$banner = "/* Generated by bin/build-forum-css.php; edit resources/forum/ instead. */\n";
$outputs = [
    'forum-base.css' => $banner
        . "@layer forum.components, application;\n\n"
        . "@layer forum.components {\n" . $read('components.css') . "}\n",
    // These tokens and rules deliberately remain unlayered. They supersede
    // the historical application layer while package and operator styles
    // retain the final position in the document's stylesheet order.
    'forum-theme.css' => $banner . $read('tokens.css') . "\n" . $read('theme.css'),
];

$stale = [];
foreach ($outputs as $name => $content) {
    $path = $root . '/public/assets/' . $name;
    if ($check) {
        if (!is_file($path) || file_get_contents($path) !== $content) {
            $stale[] = $name;
        }
    } elseif (file_put_contents($path, $content) !== strlen($content)) {
        throw new RuntimeException('Cannot write Forum asset: ' . $name);
    }
}
if ($stale !== []) {
    fwrite(STDERR, 'Forum assets need rebuilding: ' . implode(', ', $stale) . "\n");
    exit(1);
}
fwrite(STDOUT, $check ? "Forum CSS is current.\n" : "Built Forum CSS.\n");
